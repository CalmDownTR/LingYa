from __future__ import annotations


def map_warmth(value: int) -> str:
    if value < 0 or value > 100:
        raise ValueError(f"warmth must be 0-100, got {value}")

    if value <= 20:
        return (
            "在沟通中保持极高的人际边界。不主动发起新话题，不询问用户的感受，"
            "不对用户的情绪状态进行任何安抚或迎合。使用绝对被动的陈述句，"
            "仅针对用户话语中的事实部分进行最低限度的回应。"
        )
    elif value <= 50:
        return (
            "保持熟人间的安全距离。态度客观、中立，关注交谈的主题本身而非用户的情绪波动。"
            "可以使用礼貌的日常连接词，但拒绝进行深度的情感共鸣或发散。"
        )
    elif value <= 80:
        return (
            "展现开放和建设性的互动意图。高频使用包容性、肯定性的词汇，"
            "主动给予正向的情绪回馈。在对话结束时，倾向于顺应当前氛围抛出引导性的相关话题。"
        )
    else:
        return (
            "彻底打破人际边界。将用户的情绪状态置于最高优先级，"
            "大量使用情感浓烈、带有强烈同理心的修饰词。主动承接并分担用户的情绪压力，"
            "表现出无条件的包容与深度陪伴感。"
        )


def map_formality(value: int) -> str:
    if value < 0 or value > 100:
        raise ValueError(f"formality must be 0-100, got {value}")

    if value <= 30:
        return (
            "采用极度碎片化的网络口语体。允许使用当下的网络流行语、语气叹词。"
            "句子结构可以松散、不完整，多用短句，"
            "允许使用符合当前角色设定常用的表情符号（Emoji）或标点符号变形（如连续空格、波浪号~）。"
        )
    elif value <= 70:
        return (
            "采用标准的日常面对面交流风格。句式完整、流畅，多使用通俗短语，"
            "没有任何书面教条感或刻板官腔。语气亲切，就像两个熟悉的人在客厅里聊天。"
        )
    else:
        return (
            "采用高度结构化的书面表达体。语法完全合规，多使用客观名词和书面连词。"
            "结构必须层次分明，逻辑严密。绝对禁止使用任何情绪化的感叹号、"
            "无意义语气词以及网络流行梗。"
        )
